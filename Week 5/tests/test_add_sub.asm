#========================================
# CPU Instruction Test
#========================================

START:

#----------------------------------------
# LOADI
#----------------------------------------

LOADI A,10
LOADI B,20
LOADI C,5
LOADI D,2

#----------------------------------------
# MOVE
#----------------------------------------

MOVE D,A

# D = 10

#----------------------------------------
# ADD
#----------------------------------------

ADD A,B,C

# A = 20 + 5 = 25

#----------------------------------------
# ADDI
#----------------------------------------

ADDI B,A,7

# B = 25 + 7 = 32

#----------------------------------------
# SUB
#----------------------------------------

SUB C,B,D

# C = 32 - 10 = 22

#----------------------------------------
# SUBI
#----------------------------------------

SUBI D,C,4

# D = 22 - 4 = 18

#----------------------------------------
# STORE / LOAD
#----------------------------------------

STORE D,50
LOAD A,50

# A = 18

#----------------------------------------
# CMP
#----------------------------------------

CMP A,D

# Z should become 1

#----------------------------------------
# Branch if Equal
#----------------------------------------

BRE EQUAL

LOADI B,111

EQUAL:

LOADI B,99

#----------------------------------------
# Shift Left
#----------------------------------------

SHIFTL C,B

# C = 99 << 1

#----------------------------------------
# Shift Right
#----------------------------------------

SHIFTR D,C

# D = C >> 1

#----------------------------------------
# Indexed Store
#----------------------------------------

LOADI A,77
LOADI C,3

STOREF A,C,20

# Memory[23] = 77

#----------------------------------------
# Indexed Load
#----------------------------------------

LOADF B,C,20

# B = Memory[23] = 77

#----------------------------------------
# Jump
#----------------------------------------

JUMP DONE

LOADI A,0

DONE:

NOOP